#include<iostream>
#include<cmath>
using namespace std;

int main() {
	cout << sqrt(36) << endl; // square of 6 = 36
	cout << pow(2,5) << endl; // 2^5 = 32
	cout << ceil(2.3) << endl; // ceiling => round up to 3
	cout << abs(-5) << endl; // absolute value abs(-5) = 5
	cout << floor(2.9) << endl; // floor => round down to 2
	cout << round(2.5) << endl; // round to the nearest => 3
	
	return 0;
}